import json
import importlib.util
import tempfile
import unittest
from pathlib import Path

from src.dataset_io import write_jsonl


class DatasetV5BuilderTest(unittest.TestCase):
    def test_build_dataset_writes_pattern_eval_and_manifest(self) -> None:
        builder_path = Path(__file__).resolve().parents[1] / "scripts" / "build_dataset_v5.py"
        spec = importlib.util.spec_from_file_location("build_dataset_v5", builder_path)
        self.assertIsNotNone(spec)
        self.assertIsNotNone(spec.loader)
        builder = importlib.util.module_from_spec(spec)  # type: ignore[arg-type]
        spec.loader.exec_module(builder)  # type: ignore[union-attr]

        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            source_dir = root / "datasets" / "v4"
            source_dir.mkdir(parents=True, exist_ok=True)

            probes = [
                {
                    "sample_id": "bound_001",
                    "text": "This is a probe sample. It is deterministic.",
                    "collection": "attack_train",
                    "ground_truth_label": None,
                }
            ]
            train_verified = [
                {
                    "sample_id": "human_001",
                    "text": "I wrote this before 2022. It has personal tone.",
                    "ground_truth_label": "human",
                    "provenance": "archived 2022",
                },
                {
                    "sample_id": "ai_001",
                    "text": "This response follows a formal technical structure.",
                    "ground_truth_label": "ai",
                    "provenance": "generated by model",
                },
            ]
            test_verified = [
                {
                    "sample_id": "mixed_001",
                    "text": "Paragraph one sounds human. Paragraph two sounds generated.",
                    "ground_truth_label": "mixed",
                    "provenance": "mixed sample",
                }
            ]

            write_jsonl(source_dir / "probes.jsonl", probes)
            write_jsonl(source_dir / "train_verified.jsonl", train_verified)
            write_jsonl(source_dir / "test_verified.jsonl", test_verified)

            original_root = builder.PROJECT_ROOT
            builder.PROJECT_ROOT = root
            try:
                out = builder.build_dataset(
                    source_version="v4",
                    target_version="v5",
                    force=True,
                    target_per_stratum=2,
                    variants_per_augmented_base=1,
                    seed=7,
                    external_corpus_config=None,
                )
            finally:
                builder.PROJECT_ROOT = original_root

            self.assertTrue((out / "pattern_eval.jsonl").exists())
            self.assertTrue((out / "manifest.json").exists())

            manifest = json.loads((out / "manifest.json").read_text(encoding="utf-8"))
            self.assertEqual(manifest["dataset_version"], "v5")
            self.assertIn("pattern_eval.jsonl", manifest["files"])
            self.assertGreater(manifest["files"]["pattern_eval.jsonl"]["record_count"], 0)


if __name__ == "__main__":
    unittest.main()
